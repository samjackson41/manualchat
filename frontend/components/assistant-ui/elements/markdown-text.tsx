// Citations come back from the model as plain `[Page 82]` text. This plugin
// rewrites each one into a link whose `#page-82` URL the `a` renderer below
// turns into a clickable badge that opens the manual viewer at that page
// (DECISIONS V1, IMPLEMENTATION Task 6).

// The marker must be a fragment: react-markdown's URL sanitizer drops an
// unknown scheme, and a stripped URL renders as a link to the current page.
const CITATION_URL_PREFIX = "#page-";
const CITATION_PATTERN = /\[Page\s+(\d+)\]/g;

type CitationNode = {
  type: string;
  value?: string;
  url?: string;
  children?: CitationNode[];
};

function splitCitations(value: string): CitationNode[] | null {
  CITATION_PATTERN.lastIndex = 0;
  const parts: CitationNode[] = [];
  let cursor = 0;
  let matched = false;
  let match: RegExpExecArray | null;
  while ((match = CITATION_PATTERN.exec(value)) !== null) {
    matched = true;
    if (match.index > cursor) {
      parts.push({ type: "text", value: value.slice(cursor, match.index) });
    }
    parts.push({
      type: "link",
      url: `${CITATION_URL_PREFIX}${match[1]}`,
      children: [{ type: "text", value: match[0] }],
    });
    cursor = match.index + match[0].length;
  }
  if (!matched) return null;
  if (cursor < value.length) {
    parts.push({ type: "text", value: value.slice(cursor) });
  }
  return parts;
}

function walkCitations(node: { children?: CitationNode[] }): void {
  const children = node.children;
  if (!children) return;
  for (let index = 0; index < children.length; index += 1) {
    const child = children[index];
    if (child.type === "text" && typeof child.value === "string") {
      const parts = splitCitations(child.value);
      if (parts) {
        children.splice(index, 1, ...parts);
        index += parts.length - 1;
        continue;
      }
    }
    if (child.children) walkCitations(child);
  }
}

const remarkCitations: Plugin<[], Root> = () => (tree) => {
  // The mdast node union is looser than the walk below needs, hence the cast.
  walkCitations(tree as unknown as { children?: CitationNode[] });
};

type MarkdownTextProps = Partial<TextMessagePartProps> & {
  components?: Parameters<typeof memoizeMarkdownComponents>[0];
  componentsByLanguage?: MarkdownTextPrimitiveProps["componentsByLanguage"];
};

const useShallowStable = <T extends Record<string, unknown> | undefined>(
  value: T,
): T => {
  const ref = useRef(value);
  if (value !== ref.current) {
    const prev = ref.current;
    const stable =
      value !== undefined &&
      prev !== undefined &&
      Object.keys(prev).length === Object.keys(value).length &&
      Object.keys(value).every((key) => prev[key] === value[key]);
    if (!stable) ref.current = value;
  }
  return ref.current;
};

const MarkdownTextImpl: FC<MarkdownTextProps> = ({
  components,
  componentsByLanguage,
}) => {
  const stableComponents = useShallowStable(components);
  const stableComponentsByLanguage = useShallowStable(componentsByLanguage);
  const markdownComponents = useMemo(() => {
    if (!stableComponents) return defaultComponents;
    return {
      ...defaultComponents,
      ...memoizeMarkdownComponents(stableComponents),
    };
  }, [stableComponents]);

  return (
    <MarkdownTextPrimitive
      remarkPlugins={[remarkGfm, remarkCitations]}
      className="aui-md"
      components={markdownComponents}
      componentsByLanguage={stableComponentsByLanguage}
      defer
    />
  );
};

export const MarkdownText = memo(MarkdownTextImpl);

const CodeHeader: FC<CodeHeaderProps> = ({ language, code }) => {
  const { isCopied, copyToClipboard } = useCopyToClipboard();
  const onCopy = () => {
    if (!code || isCopied) return;
    copyToClipboard(code);
  };

  return (
    <div className="aui-code-header-root border-border/50 bg-muted/50 mt-3 flex items-center justify-between rounded-t-xl border border-b-0 px-3.5 py-1.5 text-xs">
      <span className="aui-code-header-language text-muted-foreground font-medium lowercase">
        {language}
      </span>
      <TooltipIconButton tooltip="Copy" onClick={onCopy}>
        {!isCopied && (
          <CopyIcon className="animate-in zoom-in-75 fade-in duration-150" />
        )}
        {isCopied && (
          <CheckIcon className="animate-in zoom-in-50 fade-in duration-200 ease-out" />
        )}
      </TooltipIconButton>
    </div>
  );
};

